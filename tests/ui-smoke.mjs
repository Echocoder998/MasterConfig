const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
await fs.mkdir('verification', { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('dialog', d => d.accept());
let responseMode = 'valid';
await context.route('**/api/ai/status', route => route.fulfill({ json: { configured: true, model: 'Mock verification' } }));
await context.route('**/api/ai/chat', async route => {
  const body = route.request().postDataJSON();
  const proposal = structuredClone(body.model);
  proposal.name = 'AI reviewed model'; proposal.notes = 'Review this proposed note.';
  proposal.status = 'draft'; proposal.steps.reverse();
  if (proposal.fields[0]?.options[0]) proposal.fields[0].options[0].orderCode = '009';
  if (proposal.rules[0]) proposal.rules.push({ ...proposal.rules[0], id: 'verification-rule-' + proposal.rules.length });
  if (responseMode === 'invalid') proposal.fields[0].options.push(proposal.fields[0].options[0]);
  await route.fulfill({ json: { reply: 'Prepared a proposal for review.', questions: ['Check the source revision.'], proposal } });
});
try {
  await page.goto((process.env.TEST_BASE_URL || 'http://127.0.0.1:3017'));
  await page.getByRole('heading', { name: 'Industrial Instrumentation, Configured with Confidence.' }).waitFor();
  assert.equal(await page.locator('.dwg-flow').evaluate(el => getComputedStyle(el).animationName), 'none');
  assert.equal(await page.locator('#chat-dock').isHidden(), true);
  await page.screenshot({ path: 'verification/hero-desktop.png' });
  await page.getByRole('button', { name: 'Help me select a thermowell.' }).click();
  assert.equal(await page.getByLabel('Message the AI').inputValue(), 'Help me select a thermowell.');
  assert.equal(await page.locator('#landing').isHidden(), true);
  await page.getByRole('button', { name: 'Collapse Flow Mind AI chat' }).click();
  await page.getByRole('button', { name: 'Daughtridge Sales Product Configurator home' }).click();
  await page.getByRole('button', { name: 'Configure a Product' }).click();
  await page.locator('#model-select').waitFor();
  await page.getByRole('button', { name: 'Admin', exact: true }).click();
  await page.getByRole('heading', { name: 'Model catalog', exact: true }).waitFor();
  await page.screenshot({ path: 'verification/catalog-desktop.png', fullPage: true });
  const count = await page.locator('#model-count').textContent();
  await page.getByLabel('Search models', { exact: true }).fill('no-match-anywhere');
  await page.getByRole('heading', { name: 'No matching models' }).waitFor();
  await page.getByRole('button', { name: 'Reset filters' }).click();
  assert.equal(await page.locator('#model-count').textContent(), count);
  await page.locator('#manufacturer-filter').selectOption('Ashcroft');
  await page.locator('#status-filter').selectOption('active');
  await page.locator('#updated-filter').selectOption('unknown');
  assert.equal(await page.locator('.catalog-table tbody tr').count(), 1);
  await page.screenshot({ path: 'verification/catalog-filtered-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Edit model', exact: true }).click();
  const originalName = await page.getByLabel('Model name', { exact: true }).inputValue();
  await page.locator('#chat-toggle').click();
  async function send() {
    await page.getByLabel('Message the AI').fill('Prepare changes');
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.getByRole('dialog').waitFor();
  }
  await send();
  await page.screenshot({ path: 'verification/proposal-desktop.png', fullPage: true });
  assert.equal(await page.getByLabel('Model name', { exact: true }).inputValue(), originalName);
  await page.getByRole('button', { name: 'Discard proposal', exact: true }).click();
  assert.equal(await page.getByLabel('Model name', { exact: true }).inputValue(), originalName);
  await send();
  await page.getByRole('button', { name: 'Close proposal review' }).click();
  await page.getByLabel('Model name', { exact: true }).fill('Manual change');
  await page.getByLabel('Model name', { exact: true }).press('Tab');
  await page.getByRole('button', { name: 'Review proposal', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Apply proposal', exact: true }).isEnabled(), false);
  await page.getByRole('button', { name: 'Refresh comparison' }).click();
  await page.getByText('Comparison refreshed against the current editor.', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Apply proposal', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'detached' });
  assert.equal(await page.getByLabel('Model name', { exact: true }).inputValue(), 'AI reviewed model');
  const unsaved = await page.evaluate(async () => (await import('/storage.js')).readStoredModel('ashcroft-1279'));
  assert.equal(unsaved, undefined);
  await page.getByRole('button', { name: 'Collapse Flow Mind AI chat' }).click();
  await page.getByRole('button', { name: 'Save as draft', exact: true }).click();
  await page.getByText('Draft saved. Activate after review to make it selectable.', { exact: true }).waitFor();
  const saved = await page.evaluate(async () => (await import('/storage.js')).readStoredModel('ashcroft-1279'));
  assert.equal(saved.name, 'AI reviewed model'); assert(saved.updatedAt.endsWith('Z')); assert.equal(saved.status, 'draft');
  await page.locator('#chat-toggle').click();
  responseMode = 'invalid'; await send();
  assert.equal(await page.getByRole('button', { name: 'Apply proposal', exact: true }).isEnabled(), false);
  await page.getByText('Cannot apply this proposal', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Discard proposal', exact: true }).click();
  responseMode = 'valid';
  await page.getByRole('button', { name: 'Collapse Flow Mind AI chat' }).click();
  await page.getByRole('button', { name: 'Model catalog', exact: true }).click();
  await page.getByRole('button', { name: 'Reset filters' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'verification/catalog-mobile.png', fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByLabel('Search models', { exact: true }).fill('AI reviewed');
  await page.getByRole('button', { name: 'Edit model', exact: true }).click();
  await page.locator('#chat-toggle').click();
  await send();
  await page.screenshot({ path: 'verification/proposal-mobile.png' });
  assert(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.getByRole('button', { name: 'Discard proposal', exact: true }).click();
  const mobile = await context.newPage();
  await mobile.setViewportSize({ width: 390, height: 844 });
  await mobile.goto((process.env.TEST_BASE_URL || 'http://127.0.0.1:3017'));
  await mobile.getByRole('heading', { name: 'Industrial Instrumentation, Configured with Confidence.' }).waitFor();
  assert(await mobile.getByRole('button', { name: 'Ask Flow Mind AI' }).isVisible());
  await mobile.screenshot({ path: 'verification/hero-mobile.png', fullPage: true });
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: desktop/mobile, reduced motion, combined filters, discard, stale refresh, apply/save separation, invalid proposals, timestamps; no page errors.');
} catch(error) { console.log('Page errors:', errors); console.log(await page.locator('body').innerText()); await page.screenshot({path:'verification/failure.png',fullPage:true}); throw error; } finally { await browser.close(); }
